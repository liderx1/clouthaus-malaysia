// the site's own wording (site.config.json → text) over the defaults above: the loading line, "Why …", the store line
for (const [l, o] of Object.entries(CONFIG.text ?? {})) {
  if (!T[l]) continue;
  if (o.loading) T[l].loading = o.loading;
  if (o.why) T[l].why = o.why;
  if (o.storeText) T[l].storeText = (name, floor, unit) => fill(o.storeText, { name, floor, unit });
  if (o.floors) T[l].floors = { ...T[l].floors, ...o.floors };
}
try {
  const l = localStorage.getItem('eko-lang');
  S.lang = T[l] && CONFIG.locales.includes(l) ? l : CONFIG.locales[0];
} catch {}
export const t = (k) => T[S.lang][k] ?? T.en[k];
export const pick = (o) => (o && typeof o === 'object' ? o[S.lang] || o.en : o);
